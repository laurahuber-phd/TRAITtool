distreact <- eventReactive(input$calc_ord, {
  runif(input$calc_ord)
  
  req(input$ord_dist)
  print(c("Ord: Distance method chosen: ", input$ord_dist))
  req(input$ord_meth)
  print(c("Ord: Ordination method chosen: ", input$ord_meth))
  
  ps <- ps.norm()
  
  success = TRUE
  readIssues <- "Ordination completed"
  
  myWarnings <- NULL
  wHandler <- function(w) {
    myWarnings <<- c(myWarnings,w)
    invokeRestart("muffleWarning")
  }
  
  ps.try <- (tryCatch( {
  ps.ord <- withCallingHandlers(
    ordinate(physeq=ps, k=3,trymax=150, maxit=500,
             method=input$ord_meth, #ordination method #c("DCA", "CCA", "RDA", "CAP", "DPCoA", "NMDS", "MDS", "PCoA")
             distance=input$ord_dist, #distance matrix
    ),
    warning=wHandler
  )
  }, error = function(e){return(NULL)}
  )
  )
pickOut <- sapply(myWarnings, function(x) class(x)=="character")
readIssues <- myWarnings[pickOut]
readIssues <- paste("Ordination failed: ",readIssues,sep="\n",collapse="\n")
    
    if(isTruthy(ps.try)) { #if ps.try is NULL, a modal dialog box will show up that reports the warning generated by ordinate, tell you that the subsetting criteria you chose will not work, and will reset the filtering selections
      ps <- ps.ord
      
      output$ord_complete <- reactive({ #tell the ui that ordination is complete
        return("Ordination complete") #print in conditional panel to show completion
      })
      outputOptions(output, 'ord_complete', suspendWhenHidden= FALSE)
      
    } else {
      output$ord_complete <- NULL
      showModal(
        modalDialog(title="ERROR",
                    print(readIssues),
                    size='l',
                    easyClose = FALSE
        )
      ) 
      shinyjs::reset("ord_meth")
      shinyjs::reset("ord_dist")
    }
    req(ps)
})

